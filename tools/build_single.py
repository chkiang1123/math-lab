#!/usr/bin/env python3
"""Build a fully self-contained single-file HTML bundle of Math Lab.

The WorkBuddy app sandbox only authorises the entry document — sibling assets
(js/, vendor/, styles.css) are refused at the edge. Inlining everything into
index.html sidesteps that completely, and makes the site work from a plain
file:// open with zero dependencies.

  index.dev.html   multi-file development version (uses vendor/ + js/)
  index.html       generated self-contained bundle  <- this is what gets deployed

Run tools/build_topics.py first — this script inlines its output.

Usage:  python3 tools/build_single.py
"""

import base64
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NODE = os.environ.get('NODE', 'node')


def read(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return f.read()


def inline_fonts(css):
    """Replace url(fonts/X.woff2) with data: URIs (woff2 only — all modern
    browsers support it, and it keeps the bundle small)."""
    def repl(m):
        name = m.group(1)
        path = os.path.join(ROOT, 'vendor', 'katex', 'fonts', name)
        with open(path, 'rb') as f:
            b64 = base64.b64encode(f.read()).decode('ascii')
        return 'url(data:font/woff2;base64,' + b64 + ')'
    return re.sub(r'url\(fonts/([^)]+\.woff2)\)', repl, css)


def guard(s):
    """Avoid an accidental </script> inside inlined JS."""
    return s.replace('</script>', '<\\/script>')


def main():
    # 0. make sure the chapter bundles are current
    subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'build_topics.py')],
                   check=True, env=dict(os.environ, NODE=NODE))

    html = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="description" content="Math Lab — practise Identities &amp; Factorization and Algebraic Fractions &amp; Formulas (Pearson 2A) with summaries, hints, step-by-step solutions and auto-generated similar questions. Works completely offline.">
<title>Math Lab — Identities &amp; Algebraic Fractions</title>
<!-- generated by tools/build_single.py — edit index.dev.html + src/ instead -->
<style>__KATEX_CSS__</style>
<style>__APP_CSS__</style>
</head>
<body>
<div id="app"></div>
<script>__KATEX_JS__</script>
<script>__SHELL__</script>
<script>__IDENTITY__</script>
<script>__FRAC__</script>
<script>__KEYPAD__</script>
</body>
</html>
"""
    out = (html
           .replace('__KATEX_CSS__', inline_fonts(read('vendor/katex/katex.min.css')))
           .replace('__APP_CSS__', read('styles.css'))
           .replace('__KATEX_JS__', guard(read('vendor/katex/katex.min.js')))
           .replace('__SHELL__', guard(read('js/shell.js')))
           .replace('__IDENTITY__', guard(read('js/topics/identity.js')))
           .replace('__FRAC__', guard(read('js/topics/frac.js')))
           .replace('__KEYPAD__', guard(read('js/keypad.js'))))

    dest = os.path.join(ROOT, 'index.html')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write(out)
    print('wrote %s (%.1f KB)' % (dest, os.path.getsize(dest) / 1024))


if __name__ == '__main__':
    sys.exit(main())
