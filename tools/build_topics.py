"""Wrap each chapter's sources into one self-contained scope.

The two chapters were developed as separate apps and their globals collide
badly (F, Poly, BANK, SETS, LEARN, rnd, gcd, parseExpr, el, route...). Putting
each chapter inside its own IIFE lets both live on one page untouched — the
verified question banks and engines stay exactly as they were tested.

    src/<topic>/{engine,gens,data,learn,app}.js  ->  js/topics/<topic>.js

Each chapter bundle is expected to define `__api` (mount/route/unmount) plus
BANK, SETS and LEARN, which the shell reads for the chapter stats.

Usage:  python3 tools/build_topics.py
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, 'js', 'topics')
FILES = ['engine.js', 'gens.js', 'data.js', 'learn.js', 'app.js']
TOPICS = ['identity', 'frac']

DECL = re.compile(r'^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)', re.M)


def declarations(src):
    return DECL.findall(src)


def build(topic):
    chunks, seen, dupes = [], {}, []
    for name in FILES:
        path = os.path.join(SRC, topic, name)
        with open(path, encoding='utf-8') as f:
            src = f.read()
        for d in declarations(src):
            if d in seen:
                dupes.append('%s (%s and %s)' % (d, seen[d], name))
            else:
                seen[d] = name
        chunks.append('/* ---------------- %s ---------------- */\n%s' % (name, src.rstrip()))

    body = '\n\n'.join(chunks)
    out = (
        '/* GENERATED by tools/build_topics.py — do not edit directly.\n'
        '   Edit src/%s/*.js instead and rebuild. */\n'
        'window.__ML.topics[%r] = (function () {\n'
        '%s\n\n'
        '  return Object.assign(__api, { BANK: BANK, SETS: SETS, LEARN: LEARN });\n'
        '})();\n' % (topic, topic, body)
    )
    dest = os.path.join(OUT, topic + '.js')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write(out)
    return dest, dupes


def main():
    os.makedirs(OUT, exist_ok=True)
    node = os.environ.get('NODE') or 'node'
    bad = 0
    for topic in TOPICS:
        dest, dupes = build(topic)
        if dupes:
            print('  ! %s: duplicate top-level names: %s' % (topic, ', '.join(dupes)))
            bad += 1
        r = subprocess.run([node, '--check', dest], capture_output=True, text=True)
        status = 'OK' if r.returncode == 0 else 'SYNTAX ERROR'
        print('%-28s %6.1f KB  %s' % (os.path.relpath(dest, ROOT),
                                      os.path.getsize(dest) / 1024, status))
        if r.returncode != 0:
            print(r.stderr[:800])
            bad += 1
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
